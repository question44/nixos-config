#!/usr/bin/env python3
"""Build home/zed/keymap.json: Zed's macOS JetBrains keymap with Cmd on Super.

On Linux, Zed's "JetBrains" base keymap is the Ctrl-based variant. This takes
the macOS keymaps for the given Zed version (default-macos.json with
macos/jetbrains.json on top, the same layering Zed uses on a Mac), rewrites
cmd- to super- and drops macOS-only window actions. settings.json sets
"base_keymap": "None" so the Linux JetBrains layer does not mix in.

Usage: python3 -I home/zed/generate-keymap.py <zed-version>   (e.g. 1.26.2)
Re-run after a Zed upgrade when its keymaps change (SYS-093).
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

BASE = "https://raw.githubusercontent.com/zed-industries/zed/v{}/assets/keymaps/{}"
SOURCES = ["default-macos.json", "macos/jetbrains.json"]
# macOS app/window management with no Linux counterpart.
DROP = {"zed::Hide", "zed::HideOthers", "zed::ShowAll", "zed::Minimize"}


def load_jsonc(text):
    text = re.sub(r"(?m)^\s*//.*$", "", text)
    text = re.sub(r"(?<=[,\[{\w\]}\"])[ \t]*//[^\n]*$", "", text, flags=re.M)
    text = re.sub(r",(\s*[}\]])", r"\1", text)
    return json.loads(text)


def to_super(keystrokes):
    return " ".join(
        "-".join("super" if part == "cmd" else part for part in stroke.split("-"))
        for stroke in keystrokes.split(" ")
    )


def action_name(action):
    return action if isinstance(action, str) or action is None else action[0]


def main():
    version = sys.argv[1]
    out = []
    for source in SOURCES:
        with urllib.request.urlopen(BASE.format(version, source)) as resp:
            blocks = load_jsonc(resp.read().decode())
        for block in blocks:
            bindings = {
                to_super(keys): action
                for keys, action in block.get("bindings", {}).items()
                if action_name(action) not in DROP
            }
            if not bindings:
                continue
            new = {k: v for k, v in block.items() if k != "bindings"}
            new["bindings"] = bindings
            out.append(new)
    header = (
        f"// Generated by home/zed/generate-keymap.py from Zed v{version}:\n"
        "// macOS default + JetBrains keymaps with Cmd on Super (SYS-093).\n"
        "// Personal overrides go at the end so a regeneration keeps them easy to find.\n"
    )
    path = Path(__file__).with_name("keymap.json")
    path.write_text(header + json.dumps(out, indent=2, ensure_ascii=False) + "\n")
    print(f"{path}: {len(out)} blocks, {sum(len(b['bindings']) for b in out)} bindings")


if __name__ == "__main__":
    main()
